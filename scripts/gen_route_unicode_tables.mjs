#!/usr/bin/env node
// Writes crates/reflex-wasm/src/route/unicode_tables.rs: the exact code point ranges of \p{Cf} and \p{Extended_Pictographic} (what the page's
// normChat removes), from the Unicode data of the running Node/ICU - so the Rust port needs no approximation and no Unicode crate.
//   node scripts/gen_route_unicode_tables.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './lib/chatbot_fns.mjs';
const ranges = re => { const out = []; let lo = -1; for (let cp = 0; cp <= 0x10FFFF + 1; cp++) { const hit = cp <= 0x10FFFF && !(cp >= 0xD800 && cp <= 0xDFFF) && re.test(String.fromCodePoint(cp)); if (hit && lo < 0) lo = cp; else if (!hit && lo >= 0) { out.push([lo, cp - 1]); lo = -1; } } return out; };
const fmt = r => r.map(([a, b]) => `    (0x${a.toString(16).toUpperCase()}, 0x${b.toString(16).toUpperCase()}),`).join('\n');
const cf = ranges(/^\p{Cf}$/u), pict = ranges(/^\p{Extended_Pictographic}$/u);
const out = `// GENERATED by scripts/gen_route_unicode_tables.mjs (Unicode ${process.versions.unicode}, ICU ${process.versions.icu}) - do not edit by hand.
// \\p{Cf} and \\p{Extended_Pictographic} as sorted inclusive code point ranges, for text::norm_chat.

pub const FORMAT: [(u32, u32); ${cf.length}] = [
${fmt(cf)}
];

pub const PICTOGRAPHIC: [(u32, u32); ${pict.length}] = [
${fmt(pict)}
];

pub fn in_ranges(table: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    table.binary_search_by(|&(lo, hi)| if cp < lo { std::cmp::Ordering::Greater } else if cp > hi { std::cmp::Ordering::Less } else { std::cmp::Ordering::Equal }).is_ok()
}
`;
const file = join(root, 'crates/reflex-wasm/src/route/unicode_tables.rs');
if (process.argv.includes('--check')) { const same = readFileSync(file, 'utf8') === out; console.log(same ? '✓ unicode_tables.rs is current' : '✗ unicode_tables.rs is stale'); process.exit(same ? 0 : 1); }
writeFileSync(file, out); console.log(`wrote ${cf.length} Cf ranges + ${pict.length} Extended_Pictographic ranges (Unicode ${process.versions.unicode})`);
