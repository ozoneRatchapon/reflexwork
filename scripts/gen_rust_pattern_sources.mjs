#!/usr/bin/env node
// Writes crates/reflex-wasm/src/resolve/patterns_src.rs: the programme-matching regexes of chatbot.html, verbatim (source + flags),
// so the Rust port cannot drift from the page by a typo. The Rust side only translates JS-only syntax (\s \d \b) when compiling.
//   node scripts/gen_rust_pattern_sources.mjs           write the file
//   node scripts/gen_rust_pattern_sources.mjs --check   exit 1 if the file is out of date (tests/rust_patterns_sync.test.mjs)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './lib/chatbot_fns.mjs';
const html = readFileSync(join(root, 'submissions/ui/chatbot.html'), 'utf8');
const one = name => { const m = html.match(new RegExp(`^const ${name}=\\/(.+)\\/([a-z]*);$`, 'm')); if (!m) throw new Error(`chatbot.html: ${name} not found`); return { src: m[1], flags: m[2] }; };
const many = (name, keyRe) => { const m = html.match(new RegExp(`^const ${name}=\\[([\\s\\S]*?)\\];\\n`, 'm')); if (!m) throw new Error(`chatbot.html: ${name} not found`);
  const items = [...m[1].matchAll(new RegExp(`\\['(${keyRe})',\\/(.+?)\\/([a-z]*)\\]`, 'g'))].map(x => ({ key: x[1], src: x[2], flags: x[3] })); if (!items.length) throw new Error(`${name}: no items`); return items; };
const raw = s => { if (s.includes('"#')) throw new Error('raw string clash'); return `r#"${s}"#`; };
const re = ({ src, flags }) => `Re { src: ${raw(src)}, flags: "${flags}" }`;
const singles = { LEAD: '_P_LEAD', TAIL: '_P_TAIL', DEGREE: '_P_DEGREE', QUAL: '_P_QUAL', OTHER: '_P_OTHER', INTENT: '_P_INTENT', FUNC: '_P_FUNC' };
const arr = (rust, ty, key, items) => `pub const ${rust}: [(${ty}, Re); ${items.length}] = [\n${items.map(i => `    (${key(i.key)}, ${re(i)}),`).join('\n')}\n];\n`;
const out = `// GENERATED by scripts/gen_rust_pattern_sources.mjs from submissions/ui/chatbot.html - do not edit by hand.
// Regenerate with: node scripts/gen_rust_pattern_sources.mjs   (tests/rust_patterns_sync.test.mjs fails when this file is stale)

/// A JavaScript regex literal: source text plus flags.
pub struct Re {
    pub src: &'static str,
    pub flags: &'static str,
}

${Object.entries(singles).map(([r, j]) => `pub const ${r}: Re = ${re(one(j))};\n`).join('')}
${arr('TOPICS', '&str', k => `"${k}"`, many('_P_TOPIC', 'fee|scholarship'))}
${arr('ASKS', '&str', k => `"${k}"`, many('_P_ASK', 'schedule|status|docs|elig|english'))}
${arr('LEVELS', 'char', k => `'${k}'`, many('_P_LEVEL', '[NCDM]'))}`;
const file = join(root, 'crates/reflex-wasm/src/resolve/patterns_src.rs');
if (process.argv.includes('--check')) { let cur = ''; try { cur = readFileSync(file, 'utf8'); } catch {} const same = cur === out; console.log(same ? '✓ patterns_src.rs matches chatbot.html' : '✗ patterns_src.rs is out of date - run node scripts/gen_rust_pattern_sources.mjs'); process.exit(same ? 0 : 1); }
writeFileSync(file, out); console.log('wrote', file);
