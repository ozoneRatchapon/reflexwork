// How often does each hand-written regex rule in chatbot.html match a question? Read-only.
// Run: node benchmark/rules/rule_hits.mjs [out.md]   -> table per rule: hits per question set + 3 example matches.
// The question pool is our TEST sets (no real-user log is read): official FAQ (th+en), odd phrasings, English held-out, beginner
// questions, the 52-query eval. A rule with 0 hits here is NOT proof it is unused by real users - only that no test exercises it.
// It counts "the regex matches the question text", not "this rule decided the answer" (branch order in _askCore is not replayed).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..'), R = f => readFileSync(join(root, f), 'utf8');
const html = R('submissions/ui/chatbot.html');

// question sets
const faq = JSON.parse(R('benchmark/field/faq_questions.json')).items;
const SETS = {
  faq_th: faq.map(x => x.th), faq_en: faq.map(x => x.en),
  odd: JSON.parse(R('benchmark/odd/odd_questions.json')).items.map(x => x.q),
  en_heldout: JSON.parse(R('benchmark/field/english_heldout.json')).items.map(x => x[0]),
  beginner: R('benchmark/coverage/beginner_questions.txt').split('\n').map(s => s.trim()).filter(s => s && !s.startsWith('#')),
  eval52: [...R('tests/kb_search.test.mjs').matchAll(/^\s*\['([^']+)',\s*(?:null|'[^']*'),\s*'[^']*'\],?$/gm)].map(m => m[1]),
};
const total = Object.values(SETS).reduce((a, s) => a + s.length, 0);

// rules: every top-level one-line `const NAME=/.../flags;` in the page (the rule constants), plus the tables of [key, /re/] pairs
const rules = [];
for (const m of html.matchAll(/^const (_?[A-Z][A-Z0-9_]*)\s*=\s*(\/.+\/[dgimsuy]*);/gm)) {
  try { rules.push({ name: m[1], re: new Function(`return ${m[2]};`)() }); } catch { rules.push({ name: m[1], re: null }); }
}
for (const m of html.matchAll(/^const (_?[A-Z][A-Z0-9_]*)\s*=\s*\[\s*\[/gm)) {
  const start = m.index + m[0].length - 2; let depth = 0, i = start;
  for (; i < html.length; i++) { if (html[i] === '[') depth++; else if (html[i] === ']' && --depth === 0) break; }
  try { const arr = new Function(`return ${html.slice(start, i + 1)};`)();
    arr.forEach(p => { const re = Array.isArray(p) ? p.find(x => x instanceof RegExp) : null; if (re) rules.push({ name: `${m[1]}[${p[0]}]`, re }); }); } catch {}
}
const hit = (re, q) => { if (!re) return false; re.lastIndex = 0; const r = re.test(q); re.lastIndex = 0; return r; };
const rows = rules.map(r => {
  const per = Object.fromEntries(Object.entries(SETS).map(([k, qs]) => [k, qs.filter(q => hit(r.re, q)).length]));
  const all = Object.values(SETS).flat().filter(q => hit(r.re, q));
  return { ...r, per, n: all.length, ex: [...new Set(all)].slice(0, 3) };
}).sort((a, b) => b.n - a.n);

const H = Object.keys(SETS);
let md = `# Rule hits on the test question pool (${total} questions)\n\n`;
md += `Generated by \`node benchmark/rules/rule_hits.mjs\` from \`submissions/ui/chatbot.html\`. ${rules.length} rules (one-line regex constants + rule tables).\n`;
md += `Counts "the regex matches the question", not "the rule decided the answer". Sets: ${H.map(k => `${k} ${SETS[k].length}`).join(', ')}.\n\n`;
md += `| rule | all | ${H.join(' | ')} | example |\n|---|---|${H.map(() => '---').join('|')}|---|\n`;
for (const r of rows) md += `| \`${r.name}\`${r.re ? '' : ' (not parsed)'} | ${r.n} | ${H.map(k => r.per[k]).join(' | ')} | ${r.ex.map(x => x.slice(0, 40).replace(/\|/g, '/')).join(' · ')} |\n`;
const zero = rows.filter(r => r.re && !r.n);
md += `\n**${zero.length} of ${rules.length} rules match no test question:** ${zero.map(r => '`' + r.name + '`').join(', ') || 'none'}.\n`;
md += `These need a test question (or a real-log check) before anyone decides they are dead; they are not proven unused.\n`;
const out = process.argv[2]; if (out) writeFileSync(out, md); console.log(md);
