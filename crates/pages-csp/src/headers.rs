//! Build the generated block of `_headers` from the pages, and splice it into the hand-written file.

use std::path::Path;

use crate::html;
use crate::policy::{self, PAGES};
use crate::types::CspError;

pub const BEGIN: &str = "# >>> pages-csp: generated by `cargo run -q -p pages-csp` from the inline scripts. Do not edit by hand; `--check` fails when stale.";
pub const END: &str = "# <<< pages-csp";

/// The generated block (markers included) for the pages in `ui`.
pub fn render(ui: &Path) -> Result<String, CspError> {
    check_folder(ui)?;
    let mut out = vec![BEGIN.to_string()];
    for page in PAGES {
        let path = ui.join(page.file);
        let text = std::fs::read_to_string(&path).map_err(|err| CspError::Io { path: path.display().to_string(), err })?;
        let scan = html::scan(&text);
        if !scan.blocked.is_empty() {
            return Err(CspError::Blocked { file: page.file.to_string(), items: scan.blocked });
        }
        let hashes: Vec<String> = scan.scripts.into_iter().map(|s| s.hash_source).collect();
        let csp = policy::csp(page, &hashes);
        for route in policy::routes(page.file) {
            out.push(route);
            if page.deny_framing {
                out.push("  X-Frame-Options: DENY".to_string());
            }
            out.push(format!("  Content-Security-Policy: {csp}"));
        }
    }
    out.push(END.to_string());
    Ok(out.join("\n"))
}

/// `current` with its generated block replaced by `block`.
pub fn splice(current: &str, block: &str) -> Result<String, CspError> {
    let (Some(b), Some(e)) = (current.find(BEGIN), current.find(END)) else { return Err(CspError::Markers) };
    if e < b {
        return Err(CspError::Markers);
    }
    Ok(format!("{}{block}{}", &current[..b], &current[e + END.len()..]))
}

/// Every `.html` in the folder has a policy, and every policy has its file.
fn check_folder(ui: &Path) -> Result<(), CspError> {
    let dir = std::fs::read_dir(ui).map_err(|err| CspError::Io { path: ui.display().to_string(), err })?;
    let mut names: Vec<String> = dir
        .filter_map(Result::ok)
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".html"))
        .collect();
    names.sort();
    if let Some(unknown) = names.iter().find(|n| policy::find(n).is_none()) {
        return Err(CspError::UnknownPage(unknown.clone()));
    }
    match PAGES.iter().find(|p| !names.iter().any(|n| n == p.file)) {
        Some(missing) => Err(CspError::MissingPage(missing.file.to_string())),
        None => Ok(()),
    }
}
