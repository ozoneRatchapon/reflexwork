//! An agency's Cloudflare Worker configs from its pack (plan 019 items 6.4 and 6.5): the LINE worker (the shared app
//! `integrations/line-worker/app.mjs` + the agency's own `kb-data.mjs`) and the kernel (gap log, votes; `integrations/kernel-worker`
//! with its own D1 database name). Placeholders only: every value the owner must create or choose is `REPLACE_...`, and no ID, URL or
//! secret of the Graduate School's deployment is ever written. Nothing here deploys.

use std::path::{Component, Path, PathBuf};

use serde_json::Value;

use crate::line_kb::render;

/// What every placeholder starts with; [`placeholders`] lists them for the owner.
pub const PLACEHOLDER: &str = "REPLACE_";

/// The Workers runtime date of the Graduate School's workers (`integrations/*/wrangler.toml`).
pub const COMPATIBILITY_DATE: &str = "2026-01-01";

/// Which configs to write.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Want {
    pub line: bool,
    pub kernel: bool,
}

/// One file to write: its path below the workers folder and its text.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
    pub rel: PathBuf,
    pub text: String,
}

/// The agency id as a Worker / D1 name part: lowercase ASCII letters, digits and `-`, 1 to 40 chars, no leading or trailing `-`.
pub fn worker_id(agency: &Value) -> Result<String, String> {
    let id = agency.get("id").and_then(Value::as_str).unwrap_or_default();
    let ok = (1..=40).contains(&id.len())
        && id.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && !id.starts_with('-')
        && !id.ends_with('-');
    match ok {
        true => Ok(id.to_string()),
        false => Err(format!("agency.json \"id\" must be 1-40 of a-z 0-9 - (a Worker name), got {id:?}")),
    }
}

/// `to` relative to the folder `from` (both absolute), with `/` separators: the import path of the shared worker code.
pub fn relative(from: &Path, to: &Path) -> String {
    let a: Vec<Component> = from.components().collect();
    let b: Vec<Component> = to.components().collect();
    let common = a.iter().zip(&b).take_while(|(x, y)| x == y).count();
    let ups = std::iter::repeat_n("..".to_string(), a.len() - common);
    let downs = b[common..].iter().map(|c| c.as_os_str().to_string_lossy().into_owned());
    ups.chain(downs).collect::<Vec<_>>().join("/")
}

/// The configs for `agency` (its `agency.json`) with the site's `index` (`knowledge-index.json`). `dir` is the absolute folder the files
/// go to (`<dir>/line`, `<dir>/kernel`) and `repo` the absolute repository root, so the entries import the shared code relatively.
pub fn files(agency: &Value, index: &[Value], index_name: &str, dir: &Path, repo: &Path, want: Want) -> Result<Vec<File>, String> {
    let id = worker_id(agency)?;
    let name = agency.get("name").and_then(Value::as_str).unwrap_or(&id).replace('"', "'");
    let mut out = Vec::new();
    if want.line {
        let app = relative(&dir.join("line"), &repo.join("integrations/line-worker/app.mjs"));
        out.push(File { rel: "line/kb-data.mjs".into(), text: render(index, index_name, Some(agency)) });
        out.push(File { rel: "line/worker.mjs".into(), text: line_entry(&name, &app) });
        out.push(File { rel: "line/wrangler.toml".into(), text: line_toml(&id, &name, want.kernel) });
    }
    if want.kernel {
        let main = relative(&dir.join("kernel"), &repo.join("integrations/kernel-worker/worker.mjs"));
        out.push(File { rel: "kernel/wrangler.toml".into(), text: kernel_toml(&id, &name, &main) });
    }
    Ok(out)
}

fn line_entry(name: &str, app: &str) -> String {
    format!(
        "// AUTO-GENERATED by pack-workers for \"{name}\" (plan 019 item 6.4): the shared LINE app with this agency's own manual.\n\
         // Regenerate with node scripts/new_agency.mjs <pack> <out> --with-line (kb-data.mjs follows the site's knowledge-index.json).\n\
         import * as MANUAL from './kb-data.mjs';\n\
         import {{ makeWorker }} from '{app}';\n\
         \n\
         // Built ONCE per isolate, at module scope (the Router, ~10 ms startup CPU), never inside a request\n\
         export default makeWorker(MANUAL).worker;\n"
    )
}

fn line_toml(id: &str, name: &str, with_kernel: bool) -> String {
    let kernel_hint = match with_kernel {
        true => "this agency's kernel (../kernel, once deployed)",
        false => "a kernel for this agency (node scripts/new_agency.mjs ... --with-kernel)",
    };
    format!(
        "# AUTO-GENERATED by pack-workers for \"{name}\" (plan 019 item 6.4). Fill every {PLACEHOLDER} value before deploying.\n\
         # Deploy (only when asked):  cd <this folder> && npx wrangler deploy   then set the LINE webhook to https://<worker>.workers.dev/webhook\n\
         name = \"reflexwork-line-{id}\"\n\
         main = \"worker.mjs\"\n\
         compatibility_date = \"{COMPATIBILITY_DATE}\"\n\
         \n\
         [vars]\n\
         KERNEL_URL = \"https://{PLACEHOLDER}kernel_host\"     # {kernel_hint}\n\
         LLM_PROXY = \"https://{PLACEHOLDER}llm_proxy_host\"   # an LLM proxy whose prompts name THIS agency (the Graduate School's proxy names itself)\n\
         SITE_ORIGIN = \"https://{PLACEHOLDER}site_host\"      # where this agency's chat page is hosted (the kernel's allowed origin)\n\
         \n\
         # Secrets (after deploy, never in this file):\n\
         #   echo \"<channel access token>\" | npx wrangler secret put LINE_CHANNEL_ACCESS_TOKEN\n\
         #   echo \"<channel secret>\"       | npx wrangler secret put LINE_CHANNEL_SECRET\n\
         \n\
         # Once the kernel runs on the same account, a service binding is the supported worker-to-worker path (KERNEL_URL stays the fallback):\n\
         # [[services]]\n\
         # binding = \"KERNEL\"\n\
         # service = \"reflexwork-kernel-{id}\"\n"
    )
}

fn kernel_toml(id: &str, name: &str, main: &str) -> String {
    format!(
        "# AUTO-GENERATED by pack-workers for \"{name}\" (plan 019 item 6.5): the kernel (question counts, gap log, votes, KB drafts) for this\n\
         # agency only, on its own D1 database. Fill every {PLACEHOLDER} value before deploying; deploy only when asked, D1 backup first.\n\
         name = \"reflexwork-kernel-{id}\"\n\
         main = \"{main}\"\n\
         compatibility_date = \"{COMPATIBILITY_DATE}\"\n\
         \n\
         [vars]\n\
         SITE_ORIGIN = \"https://{PLACEHOLDER}site_host\"   # the only site allowed to call this kernel from a browser\n\
         \n\
         # Create the database, then paste its id:  npx wrangler d1 create reflexwork-{id}\n\
         [[d1_databases]]\n\
         binding = \"DB\"\n\
         database_name = \"reflexwork-{id}\"\n\
         database_id = \"{PLACEHOLDER}d1_database_id\"\n\
         \n\
         # Secret (after deploy): echo \"<staff token>\" | npx wrangler secret put STAFF_TOKEN   (the dashboard's staff calls)\n\
         \n\
         # /kb-autodraft calls an LLM proxy worker-to-worker; without this binding the daily auto-draft does nothing for this agency.\n\
         # [[services]]\n\
         # binding = \"LLM_PROXY_SVC\"\n\
         # service = \"{PLACEHOLDER}llm_proxy_worker\"\n\
         \n\
         # Daily: retention prune and the auto-draft of top gaps, 02:00 UTC (09:00 Bangkok)\n\
         [triggers]\n\
         crons = [\"0 2 * * *\"]\n"
    )
}

/// Every `REPLACE_...` placeholder still in `files`, as `path: NAME`, for the owner's to-do list.
pub fn placeholders(files: &[File]) -> Vec<String> {
    let mut out = Vec::new();
    for f in files.iter().filter(|f| f.rel.extension().is_some_and(|e| e == "toml")) {
        for line in f.text.lines().filter(|l| !l.trim_start().starts_with('#')) {
            if let Some(i) = line.find(PLACEHOLDER) {
                let word: String = line[i..].chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
                out.push(format!("{}: {word}", f.rel.display()));
            }
        }
    }
    out
}
